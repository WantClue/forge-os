#!/bin/bash
# Regenerates main/certs/ca_bundle.pem from ESP-IDF's default certificate
# bundle, minus every root owned by eMudhra (emSign). eMudhra's intermediate
# CA keys were compromised in October 2026:
# https://blog.cloudflare.com/emudhra-certificate-compromise
#
# Run again after bumping ESP-IDF so the bundle tracks upstream.
#
# TODO(idf-bump): temporary. Once CI is on an ESP-IDF release whose default
# bundle no longer has "emSign ECC Root CA - G3" (v6.0.4+, or v6.1.x with the
# backport), delete this script, main/certs/ and the custom bundle lines in
# sdkconfig.defaults. Check with:
#   curl -fsSL https://raw.githubusercontent.com/espressif/esp-idf/<tag>/components/mbedtls/esp_crt_bundle/cacrt_all.pem | grep -c 'emSign ECC Root CA - G3'
# Usage: ./update_ca_bundle.sh [idf_tag]
#     idf_tag: e.g. v6.0.2 (default: the idf version in dependencies.lock)

set -euo pipefail

IDF_TAG=${1:-v$(awk '/^  idf:/ { f = 1 } f && /version:/ { print $2; exit }' dependencies.lock)}
BASE_URL="https://raw.githubusercontent.com/espressif/esp-idf/${IDF_TAG}/components/mbedtls/esp_crt_bundle"
OUT="main/certs/ca_bundle.pem"
EXCLUDE="eMudhra|emSign"

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

curl -fsSL "$BASE_URL/cacrt_all.pem" -o "$TMP/all.pem"
curl -fsSL "$BASE_URL/cacrt_local.pem" -o "$TMP/local.pem"

# Split into one file per certificate
cat "$TMP/all.pem" "$TMP/local.pem" | awk -v dir="$TMP" '
    /-----BEGIN CERTIFICATE-----/ { n++; f = sprintf("%s/cert%04d.pem", dir, n) }
    f { print > f }
    /-----END CERTIFICATE-----/ { close(f); f = "" }'

mkdir -p "$(dirname "$OUT")"
{
    echo "# ESP-IDF ${IDF_TAG} certificate bundle without eMudhra/emSign roots."
    echo "# Generated by update_ca_bundle.sh, do not edit by hand."
} > "$OUT"

kept=0
dropped=0
for cert in "$TMP"/cert*.pem; do
    subject=$(openssl x509 -in "$cert" -noout -subject)
    if echo "$subject" | grep -qiE "$EXCLUDE"; then
        echo "Dropping: $subject"
        dropped=$((dropped + 1))
        continue
    fi
    echo "" >> "$OUT"
    cat "$cert" >> "$OUT"
    kept=$((kept + 1))
done

echo "Wrote $OUT: $kept kept, $dropped dropped"
